# Regenerates runtime/kernel/imports.inc from the recompiler output.
# Run from the repo root after every XenonRecomp run:
#   powershell -ExecutionPolicy Bypass -File tools\gen-imports.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$shared = Join-Path $root 'generated\ppc_recomp_shared.h'
$krnlTable = Join-Path $root 'tools\XenonRecomp\XenonUtils\xbox\xboxkrnl_table.inc'
$out = Join-Path $root 'runtime\kernel\imports.inc'

$names = Select-String -Path $shared -Pattern 'PPC_EXTERN_FUNC\(__imp__(\w+)\)' |
    ForEach-Object { $_.Matches[0].Groups[1].Value } | Sort-Object -Unique
$krnl = @{}
Select-String -Path $krnlTable -Pattern 'XE_EXPORT\(xboxkrnl, 0x\w+, (\w+),' |
    ForEach-Object { $krnl[$_.Matches[0].Groups[1].Value] = $true }

$lines = @(
    '// Generated by tools/gen-imports.ps1 from generated/ppc_recomp_shared.h - do not edit.'
    '// IMPORT(library, name): every xboxkrnl/xam function the game calls.'
    '// Real implementations live in runtime/kernel/*.cpp; anything not implemented'
    '// falls back to the logging stub in runtime/kernel/stubs.cpp.'
)
foreach ($n in $names) {
    $lib = if ($krnl.ContainsKey($n)) { 'xboxkrnl' } else { 'xam' }
    $lines += "IMPORT($lib, $n)"
}
Set-Content -Path $out -Value $lines -Encoding ascii
Write-Host ("imports.inc: {0} imports ({1} xboxkrnl, {2} xam)" -f $names.Count,
    ($names | Where-Object { $krnl.ContainsKey($_) }).Count,
    ($names | Where-Object { -not $krnl.ContainsKey($_) }).Count)
