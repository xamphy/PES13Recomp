# Call-graph survey of an address window (default: the Direct3D library) built from
# the recompiled code. For every function in the window: size, callers from outside
# vs inside the window, callees, imports. Functions mostly called from outside are the
# library's API surface - the candidates to hook.
#   powershell -ExecutionPolicy Bypass -File tools\d3d-survey.ps1 [-Lo 0x822C0000] [-Hi 0x82330000]
param([string]$Lo = '0x822C0000', [string]$Hi = '0x82330000', [string]$Out = 'docs\d3d-survey.md')
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $MyInvocation.MyCommand.Path -Parent) -Parent

Add-Type -Language CSharp -TypeDefinition @'
using System; using System.IO; using System.Linq; using System.Collections.Generic; using System.Text; using System.Text.RegularExpressions;
public static class Survey {
  public static string Run(string generatedDir, uint lo, uint hi) {
    var calls = new Dictionary<uint, HashSet<uint>>();      // caller -> callees
    var callers = new Dictionary<uint, List<uint>>();       // callee -> call sites (caller funcs)
    var imports = new Dictionary<uint, SortedSet<string>>();
    var size = new Dictionary<uint, int>();                  // lines of generated code
    var callRx = new Regex(@"^\t(?:return )?sub_([0-9A-F]{8})\(ctx, base\);");
    var impRx = new Regex(@"^\t__imp__(\w+)\(ctx, base\);");
    foreach (var file in Directory.GetFiles(generatedDir, "ppc_recomp.*.cpp")) {
      uint fn = 0;
      foreach (var line in File.ReadLines(file)) {
        if (line.StartsWith("PPC_FUNC_IMPL(__imp__sub_")) { fn = Convert.ToUInt32(line.Substring(25, 8), 16); calls[fn] = new HashSet<uint>(); imports[fn] = new SortedSet<string>(); size[fn] = 0; continue; }
        if (fn == 0) continue;
        size[fn]++;
        var m = callRx.Match(line);
        if (m.Success) { uint t = Convert.ToUInt32(m.Groups[1].Value, 16); calls[fn].Add(t); List<uint> l; if (!callers.TryGetValue(t, out l)) callers[t] = l = new List<uint>(); l.Add(fn); continue; }
        m = impRx.Match(line);
        if (m.Success) imports[fn].Add(m.Groups[1].Value);
      }
    }
    var sb = new StringBuilder();
    sb.AppendLine(string.Format("# Call-graph survey 0x{0:X8}-0x{1:X8}", lo, hi));
    sb.AppendLine();
    sb.AppendLine("Generated by tools/d3d-survey.ps1 from the recompiled code. `ext` = call sites in functions outside the window, `int` = inside. Indirect calls (vtables, function pointers) are not counted.");
    sb.AppendLine();
    sb.AppendLine("| function | lines | ext | int | callees | imports | external caller sample |");
    sb.AppendLine("|---|---:|---:|---:|---:|---|---|");
    foreach (var fn in calls.Keys.Where(f => f >= lo && f < hi).OrderBy(f => f)) {
      List<uint> cs; callers.TryGetValue(fn, out cs); cs = cs ?? new List<uint>();
      int ext = cs.Count(c => c < lo || c >= hi), inn = cs.Count - ext;
      var sample = string.Join(" ", cs.Where(c => c < lo || c >= hi).Distinct().Take(3).Select(c => c.ToString("X8")));
      sb.AppendLine(string.Format("| {0:X8} | {1} | {2} | {3} | {4} | {5} | {6} |", fn, size[fn], ext, inn, calls[fn].Count,
        string.Join(", ", imports[fn]), sample));
    }
    return sb.ToString();
  }
}
'@

$text = [Survey]::Run("$root\generated", [Convert]::ToUInt32(($Lo -replace '^0x',''), 16), [Convert]::ToUInt32(($Hi -replace '^0x',''), 16))
Set-Content -Path (Join-Path $root $Out) -Value $text -Encoding utf8
Write-Host "wrote $Out ($(($text -split "`n").Count) lines)"
