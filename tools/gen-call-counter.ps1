# Generates runtime/debug/call_counter.gen.cpp: a strong override for every recompiled
# function in an address window that counts its calls and then runs the original
# (__imp__sub_X). Because sub_X is a weak alias, this catches direct calls AND calls
# through function pointers (the lookup table also points at sub_X).
#   powershell -ExecutionPolicy Bypass -File tools\gen-call-counter.ps1 [-Lo 0x822E0000] [-Hi 0x82304000] [-Exclude 822E9380,...]
# Excluded functions can have a hand-written override (see runtime/debug/).
param([string]$Lo = '0x822E0000', [string]$Hi = '0x82304000', [string[]]$Exclude = @())
$ErrorActionPreference = 'Stop'
$root = Split-Path (Split-Path $MyInvocation.MyCommand.Path -Parent) -Parent
$lo = [Convert]::ToUInt32(($Lo -replace '^0x', ''), 16)
$hi = [Convert]::ToUInt32(($Hi -replace '^0x', ''), 16)
$Exclude = @($Exclude | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim().ToUpper() -replace '^0X', '' } | Where-Object { $_ })
# Functions with a hand-written override anywhere in runtime\ are excluded automatically.
$Exclude += @(Get-ChildItem "$root\runtime" -Recurse -Include *.cpp | Where-Object { $_.Name -notlike '*.gen.cpp' } |
    Select-String -Pattern '^PPC_FUNC\(sub_([0-9A-F]{8})\)' | ForEach-Object { $_.Matches[0].Groups[1].Value })
if ($Exclude.Count) { Write-Host "excluded: $($Exclude | Sort-Object -Unique)" }

$funcs = Select-String -Path "$root\generated\ppc_func_mapping.cpp" -Pattern '\{ 0x([0-9A-F]+), sub_' |
    ForEach-Object { [Convert]::ToUInt32($_.Matches[0].Groups[1].Value, 16) } |
    Where-Object { $_ -ge $lo -and $_ -lt $hi -and ($Exclude -notcontains ('{0:X8}' -f $_)) } | Sort-Object -Unique

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Generated by tools/gen-call-counter.ps1 - do not edit.')
[void]$sb.AppendLine(('// Window 0x{0:X8}-0x{1:X8}, {2} functions.' -f $lo, $hi, $funcs.Count))
[void]$sb.AppendLine('#include "call_counter.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const uint32_t g_callCounterAddresses[] = {')
foreach ($f in $funcs) { [void]$sb.AppendLine(('    0x{0:X8},' -f $f)) }
[void]$sb.AppendLine('};')
[void]$sb.AppendLine(('const uint32_t g_callCounterCount = {0};' -f $funcs.Count))
[void]$sb.AppendLine(('std::atomic<uint32_t> g_callCounters[{0}];' -f $funcs.Count))
[void]$sb.AppendLine('')
$i = 0
foreach ($f in $funcs) {
    $n = 'sub_{0:X8}' -f $f
    [void]$sb.AppendLine(('extern "C" PPC_FUNC(__imp__{0}); PPC_FUNC({0}) {{ g_callCounters[{1}].fetch_add(1, std::memory_order_relaxed); __imp__{0}(ctx, base); }}' -f $n, $i))
    $i++
}
New-Item -ItemType Directory -Force "$root\runtime\debug" | Out-Null
Set-Content -Path "$root\runtime\debug\call_counter.gen.cpp" -Value $sb.ToString() -Encoding ascii
Write-Host "call_counter.gen.cpp: $($funcs.Count) functions"
